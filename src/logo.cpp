void drawLogoScaled(TFT_eSPI &tft, int16_t x, int16_t y,
                    int16_t w, int16_t h) {
    if (w <= 0 || h <= 0 || w > 240) return;

    static uint16_t line[240];
    const int16_t bytesPerRow = (LOGO_SOURCE_W + 7) / 8;

    for (int16_t dy = 0; dy < h; ++dy) {
        const int16_t sy = (int32_t)dy * LOGO_SOURCE_H / h;

        for (int16_t dx = 0; dx < w; ++dx) {
            const int16_t sx = (int32_t)dx * LOGO_SOURCE_W / w;
            const size_t index = (size_t)sy * bytesPerRow + (sx >> 3);
            const uint8_t packed = pgm_read_byte(&logoBitmap[index]);
            const bool on = (packed & (0x80 >> (sx & 7))) != 0;
            line[dx] = on ? TFT_WHITE : TFT_BLACK;
        }

        tft.pushImage(x, y + dy, w, 1, line);
    }
}

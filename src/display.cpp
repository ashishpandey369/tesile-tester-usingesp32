static inline uint16_t alphaTo565(uint8_t a)
{
    const uint16_t r = (uint16_t(a) * 31 + 127) / 255;
    const uint16_t g = (uint16_t(a) * 63 + 127) / 255;
    const uint16_t b = (uint16_t(a) * 31 + 127) / 255;
    return (r << 11) | (g << 5) | b;
}

static void draw4BitLogo(TFT_eSPI &tft, const uint8_t *bitmap, int16_t x, int16_t y, int16_t w, int16_t h)
{
    static uint16_t line[400];
    for (int16_t row = 0; row < h; ++row)
    {
        for (int16_t col = 0; col < w; ++col)
        {
            const uint8_t packed = pgm_read_byte(bitmap + (row * w + col) / 2);
            const uint8_t level = (col & 1) ? (packed & 0x0F) : (packed >> 4);
            line[col] = alphaTo565(level * 17);
        }
        tft.pushImage(x, y + row, w, 1, line);
    }
}

void DisplayManager::begin()
{
    tft.init(); tft.setRotation(DISPLAY_ROTATION); tft.fillScreen(TFT_BLACK); tft.setTextWrap(false); showBootScreen();
}
void DisplayManager::update()
{
    if (millis() - lastRefresh < DISPLAY_REFRESH_MS) return; lastRefresh = millis(); if (!layoutDrawn) return;
    drawForce(); drawMode(); drawMotor(); drawStatus();
}
void DisplayManager::clear()
{
    tft.fillScreen(TFT_BLACK); layoutDrawn = false; lastForce = -9999.0f; lastMode = ""; lastMotor = ""; lastStatus = "";
}
void DisplayManager::showBootScreen()
{
    clear(); tft.fillScreen(TFT_BLACK); draw4BitLogo(tft, startupLogo4, STARTUP_X, STARTUP_Y, STARTUP_W, STARTUP_H);
    tft.setTextDatum(MC_DATUM); tft.setTextColor(TFT_WHITE, TFT_BLACK); tft.drawCentreString("Initializing...", 240, 238, 4); delay(3000); showHomeScreen();
}
void DisplayManager::showHomeScreen()
{
    clear(); currentForce = INITIAL_CURRENT_FORCE; mode = "TENSILE"; motorStatus = "STOP"; machineStatus = "READY";
    drawLayout(); drawForce(); drawMode(); drawMotor(); drawStatus();
}
void DisplayManager::showErrorScreen(const String &msg)
{
    clear(); tft.setTextDatum(MC_DATUM); tft.setTextColor(TFT_RED, TFT_BLACK); tft.drawCentreString("SYSTEM STOP", 240, 72, 4);
    tft.setTextColor(TFT_WHITE, TFT_BLACK); tft.drawCentreString(msg, 240, 135, 2); tft.drawCentreString("TURN SWITCH OFF", 240, 200, 2); tft.drawCentreString("AND RESTART", 240, 228, 2);
}
void DisplayManager::drawLogo()
{
    tft.fillRect(LOGO_X, LOGO_Y, LOGO_W, LOGO_H, TFT_BLACK); draw4BitLogo(tft, headerLogo4, LOGO_X, LOGO_Y, LOGO_W, LOGO_H);
}
void DisplayManager::drawLayout()
{
    layoutDrawn = true; tft.fillScreen(TFT_BLACK); tft.setTextDatum(TL_DATUM); tft.drawRoundRect(OUTER_X, OUTER_Y, OUTER_W, OUTER_H, 5, TFT_WHITE);
    drawLogo(); tft.setTextDatum(MC_DATUM); tft.setTextColor(TFT_YELLOW, TFT_BLACK); tft.drawCentreString("PUSH/PULL TESTER", 300, 25, 4); tft.drawCentreString("PUSH/PULL TESTER", 301, 25, 4);
    tft.drawFastHLine(OUTER_X + 8, HEADER_LINE_Y, OUTER_W - 16, TFT_DARKGREY);
    tft.drawRoundRect(LEFT_X, TOP_Y, CELL_W, CELL_H, 5, TFT_WHITE); tft.drawRoundRect(RIGHT_X, TOP_Y, CELL_W, CELL_H, 5, TFT_WHITE);
    tft.drawRoundRect(LEFT_X, BOTTOM_Y, CELL_W, CELL_H, 5, TFT_WHITE); tft.drawRoundRect(RIGHT_X, BOTTOM_Y, CELL_W, CELL_H, 5, TFT_WHITE);
    tft.setTextColor(TFT_LIGHTGREY, TFT_BLACK); tft.drawCentreString("CURRENT FORCE", LEFT_X + CELL_W / 2, TOP_Y + 17, 2); tft.drawCentreString("MODE", RIGHT_X + CELL_W / 2, TOP_Y + 17, 2);
    tft.drawCentreString("MOTOR", LEFT_X + CELL_W / 2, BOTTOM_Y + 17, 2); tft.drawCentreString("MACHINE STATUS", RIGHT_X + CELL_W / 2, BOTTOM_Y + 17, 2);
}
void DisplayManager::drawForce()
{
    if (currentForce == lastForce) return; lastForce = currentForce; const int16_t x=LEFT_X+4,y=TOP_Y+34,w=CELL_W-8,h=CELL_H-39; tft.fillRect(x,y,w,h,TFT_BLACK);
    String value=String(currentForce,3),unit="kg"; const uint8_t valueFont=6,unitFont=4; const int16_t gap=5; int16_t valueW=tft.textWidth(value,valueFont),unitW=tft.textWidth(unit,unitFont),totalW=valueW+gap+unitW,startX=LEFT_X+(CELL_W-totalW)/2,centerY=TOP_Y+CELL_H/2+4;
    tft.setTextDatum(ML_DATUM); tft.setTextColor(TFT_CYAN,TFT_BLACK); tft.drawString(value,startX,centerY,valueFont); tft.setTextColor(TFT_WHITE,TFT_BLACK); tft.drawString(unit,startX+valueW+gap,centerY,unitFont);
}
void DisplayManager::drawMode()
{
    if(mode==lastMode)return; lastMode=mode; tft.fillRect(RIGHT_X+4,TOP_Y+34,CELL_W-8,CELL_H-39,TFT_BLACK); tft.setTextDatum(MC_DATUM); tft.setTextColor(mode=="TENSILE"?TFT_GREEN:TFT_ORANGE,TFT_BLACK); tft.drawCentreString(mode,RIGHT_X+CELL_W/2,TOP_Y+CELL_H/2+4,4);
}
void DisplayManager::drawMotor()
{
    if(motorStatus==lastMotor)return; lastMotor=motorStatus; tft.fillRect(LEFT_X+4,BOTTOM_Y+34,CELL_W-8,CELL_H-39,TFT_BLACK); String displayMotor=motorStatus; uint16_t color=TFT_YELLOW;
    if(motorStatus=="UP"){displayMotor="DOWN";color=TFT_RED;} else if(motorStatus=="DOWN"){displayMotor="UP";color=TFT_GREEN;}
    tft.setTextDatum(MC_DATUM); tft.setTextColor(color,TFT_BLACK); tft.drawCentreString(displayMotor,LEFT_X+CELL_W/2,BOTTOM_Y+CELL_H/2+4,4);
}
void DisplayManager::drawStatus()
{
    if(machineStatus==lastStatus)return; lastStatus=machineStatus; tft.fillRect(RIGHT_X+4,BOTTOM_Y+34,CELL_W-8,CELL_H-39,TFT_BLACK); uint16_t color=TFT_WHITE;
    if(machineStatus=="READY")color=TFT_GREEN; else if(machineStatus=="RUNNING")color=TFT_CYAN; else if(machineStatus=="STOP")color=TFT_RED; else if(machineStatus=="TURN OFF")color=TFT_ORANGE;
    tft.setTextDatum(MC_DATUM); tft.setTextColor(color,TFT_BLACK); tft.drawCentreString(machineStatus,RIGHT_X+CELL_W/2,BOTTOM_Y+CELL_H/2+4,4);
}
void DisplayManager::setCurrentForce(float value){if(value<0.0f)value=0.0f;if(value>MAX_VIRTUAL_FORCE_KG)value=MAX_VIRTUAL_FORCE_KG;currentForce=value;}
void DisplayManager::setMode(const String &newMode){mode=newMode;}
void DisplayManager::setMotorStatus(const String &status){motorStatus=status;}
void DisplayManager::setMachineStatus(const String &status){machineStatus=status;}
